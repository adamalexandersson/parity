<?php

use Illuminate\Support\Facades\File;
use Sprout\Contracts\Host;
use Sprout\Host\LaravelHost;
use Sprout\Schema\Version;
use Sprout\Tests\Support\FakeHost;

beforeEach(function () {
    $this->outputRelative = 'storage/framework/sprout-tests/'.uniqid('run_', true);
    File::ensureDirectoryExists(base_path($this->outputRelative));

    config([
        'sprout.components.path' => __DIR__.'/fixtures',
        'sprout.components.namespace' => 'Sprout\\Tests\\Fixtures',
        'sprout.editor.manifest_path' => $this->outputRelative.'/manifest.json',
    ]);
});

afterEach(function () {
    $path = base_path($this->outputRelative ?? '');

    if ($path !== base_path() && File::isDirectory($path)) {
        File::deleteDirectory($path);
    }
});

it('writes a committed manifest with reflected constructor props', function () {
    $this->artisan('sprout:manifest')
        ->assertSuccessful();

    $path = base_path($this->outputRelative.'/manifest.json');

    expect($path)->toBeFile();

    $manifest = json_decode(File::get($path), true, 512, JSON_THROW_ON_ERROR);

    expect($manifest['schemaVersion'])->toBe(Version::CURRENT)
        ->and($manifest['components'])->toHaveKey('reflect-props-test')
        ->and($manifest['components']['reflect-props-test']['exportName'])->toBe('ReflectPropsTest')
        ->and($manifest['components']['reflect-props-test']['class'])->toBe(
            'Sprout\\Tests\\Fixtures\\ReflectPropsTestComponent'
        )
        ->and($manifest['components']['reflect-props-test']['props'])->toContain([
            'name' => 'size',
            'type' => 'string',
            'default' => 'md',
            'required' => false,
        ]);
});

it('fails doctor when the manifest drifts from discovered schemas', function () {
    $manifestPath = base_path($this->outputRelative.'/manifest.json');
    File::put($manifestPath, json_encode([
        'generatedAt' => now()->toIso8601String(),
        'schemaVersion' => Version::CURRENT,
        'components' => [
            'shell-structure-test' => [
                'exportName' => 'ShellStructureTest',
                'class' => 'Sprout\\Tests\\Fixtures\\ShellStructureTestComponent',
                'props' => [],
            ],
        ],
    ], JSON_THROW_ON_ERROR));

    $this->artisan('sprout:doctor')
        ->assertFailed();
});

it('resolves safelist output through the laravel host base path', function () {
    expect(app(Host::class))->toBeInstanceOf(LaravelHost::class);

    $relative = $this->outputRelative.'/safelist.css';
    $path = base_path($relative);

    $this->artisan('sprout:safelist', ['--output' => $relative])
        ->assertSuccessful();

    expect($path)->toBeFile()
        ->and(File::get($path))->toContain('Auto-generated by sprout:safelist');
});

it('uses fake host path resolution for adapter doubles', function () {
    $host = new FakeHost('/var/theme');

    expect($host->path('resources/js/sprout/manifest.json'))
        ->toBe('/var/theme/resources/js/sprout/manifest.json')
        ->and($host->escUrl('media/a.png'))->toBe('https://example.test/media/a.png')
        ->and($host->filter('sprout/test', 'x'))->toBe('x');

    $host->listen('sprout/test', fn ($value) => $value.'-y');

    expect($host->filter('sprout/test', 'x'))->toBe('x-y');
});
